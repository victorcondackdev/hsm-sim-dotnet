// Command vecgen generates the cross-language parity vectors used by the C#
// test suite. It runs the Go implementation
// (github.com/victorcondackdev/hsm-sim-go) over a deterministic corpus and
// writes the outputs as C# literals.
//
// Usage, from the repository root, with the Go module cloned next to it:
//
//	go -C tools/vecgen run . > tests/HsmSim.Tests/Parity/GoVectors.g.cs
package main

import (
	"bytes"
	"fmt"
	"math/rand"
	"os"
	"strings"

	"github.com/victorcondackdev/hsm-sim-go/cardauth"
	"github.com/victorcondackdev/hsm-sim-go/dukpt"
	"github.com/victorcondackdev/hsm-sim-go/emv"
	"github.com/victorcondackdev/hsm-sim-go/fpe"
	"github.com/victorcondackdev/hsm-sim-go/keys"
	"github.com/victorcondackdev/hsm-sim-go/pinblock"
	"github.com/victorcondackdev/hsm-sim-go/tokenize"
)

var rng = rand.New(rand.NewSource(20261127))

func bytesN(n int) []byte {
	b := make([]byte, n)
	rng.Read(b)
	return b
}

func hx(b []byte) string { return `"` + keys.HexUpper(b) + `"` }
func q(s string) string  { return fmt.Sprintf("%q", s) }

func digits(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteByte(byte('0' + rng.Intn(10)))
	}
	return b.String()
}

func luhnPAN(n int) string {
	body := digits(n - 1)
	for d := byte('0'); d <= '9'; d++ {
		if tokenize.Luhn(body + string(d)) {
			return body + string(d)
		}
	}
	panic("unreachable")
}

func must[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}

type out struct{ b bytes.Buffer }

func (o *out) f(format string, a ...any) { fmt.Fprintf(&o.b, format, a...) }

func main() {
	o := &out{}
	o.f("// <auto-generated>\n// Generated by tools/vecgen from the Go implementation (github.com/victorcondackdev/hsm-sim-go).\n")
	o.f("// Do not edit by hand; regenerate with: go -C tools/vecgen run . > tests/HsmSim.Tests/Parity/GoVectors.g.cs\n// </auto-generated>\n\n")
	o.f("namespace HsmSim.Tests.Parity;\n\ninternal static class GoVectors\n{\n")

	// Key check values and MACs.
	o.f("    public static readonly (string Key, string Kcv)[] TdesKcv =\n    {\n")
	for i := 0; i < 12; i++ {
		k := keys.FixParity(bytesN([]int{8, 16, 24}[i%3]))
		o.f("        (%s, %s),\n", hx(k), q(must(keys.KCV(k))))
	}
	o.f("    };\n\n")

	o.f("    public static readonly (string Key, string Data, string Cmac, string KcvAes)[] AesCmac =\n    {\n")
	for i := 0; i < 12; i++ {
		k := bytesN([]int{16, 24, 32}[i%3])
		d := bytesN(rng.Intn(70))
		o.f("        (%s, %s, %s, %s),\n", hx(k), hx(d), hx(must(keys.CMAC(k, d))), q(must(keys.KCVAES(k))))
	}
	o.f("    };\n\n")

	o.f("    public static readonly (string Key, string Data, int Padding, string Retail, string CbcMac, string TdesCmac)[] Macs =\n    {\n")
	for i := 0; i < 16; i++ {
		k := keys.FixParity(bytesN(16))
		d := bytesN(rng.Intn(40))
		p := keys.Padding(1 + i%2)
		o.f("        (%s, %s, %d, %s, %s, %s),\n", hx(k), hx(d), p, hx(must(keys.RetailMAC(k, d, p))), hx(must(keys.CBCMAC(k, d, p))), hx(must(keys.TDESCMAC(k, d))))
	}
	o.f("    };\n\n")

	// PIN blocks with a deterministic fill source.
	o.f("    public static readonly (int Format, string Key, string Pin, string Pan, string Fill, string Clear, string Encrypted)[] PinBlocks =\n    {\n")
	for i := 0; i < 40; i++ {
		f := pinblock.Format(i % 5)
		var k []byte
		if f == pinblock.Format4 {
			k = bytesN(16)
		} else {
			k = keys.FixParity(bytesN(16))
		}
		pin := digits(4 + rng.Intn(9))
		pan := luhnPAN(13 + rng.Intn(7))
		fill := bytesN(16)
		clear := must(pinblock.Encode(f, pin, pan, bytes.NewReader(fill)))
		enc := must(pinblock.EncryptClear(f, k, clear, pan))
		o.f("        (%d, %s, %s, %s, %s, %s, %s),\n", f, hx(k), q(pin), q(pan), hx(fill), hx(clear), hx(enc))
	}
	o.f("    };\n\n")

	// DUKPT.
	o.f("    public static readonly (string Bdk, string Ksn, string Ipek, string Transaction, string Pin, string MacRequest, string MacResponse, string DataRequest, string DataResponse)[] Dukpt =\n    {\n")
	for i := 0; i < 20; i++ {
		bdk := keys.FixParity(bytesN(16))
		var ks dukpt.KSN
		copy(ks[:], bytesN(10))
		c := uint32(rng.Intn(dukpt.MaxCounter + 1))
		if i < 3 {
			c = uint32(i + 1)
		}
		ks = ks.WithCounter(c)
		ipek := must(dukpt.IPEK(bdk, ks))
		tx := must(dukpt.Derive(bdk, ks))
		o.f("        (%s, %q, %s, %s", hx(bdk), ks.String(), hx(ipek), hx(tx))
		for u := dukpt.PIN; u <= dukpt.DataResponse; u++ {
			o.f(", %s", hx(must(dukpt.WorkingKey(tx, u))))
		}
		o.f("),\n")
	}
	o.f("    };\n\n")

	// Card verification.
	o.f("    public static readonly (string Key, string Pan, string Expiry, string Service, string Cvv)[] Cvv =\n    {\n")
	for i := 0; i < 20; i++ {
		k := keys.FixParity(bytesN(16))
		pan := luhnPAN(13 + rng.Intn(7))
		exp := fmt.Sprintf("%02d%02d", 26+rng.Intn(10), 1+rng.Intn(12))
		svc := []string{"101", "201", "000", "999"}[i%4]
		o.f("        (%s, %q, %q, %q, %q),\n", hx(k), pan, exp, svc, must(cardauth.CVV(k, pan, exp, svc)))
	}
	o.f("    };\n\n")

	o.f("    public static readonly (string Key, string Pan, int Pvki, string Pin, string Pvv, string Natural, string Offset)[] PinVerification =\n    {\n")
	for i := 0; i < 20; i++ {
		k := keys.FixParity(bytesN(16))
		pan := luhnPAN(13 + rng.Intn(7))
		pin := digits(4 + rng.Intn(9))
		pvki := rng.Intn(7)
		s := cardauth.IBM3624{Key: k}
		o.f("        (%s, %q, %d, %q, %q, %q, %q),\n", hx(k), pan, pvki, pin,
			must(cardauth.PVV(k, pan, pvki, pin)), must(s.NaturalPIN(pan, len(pin))), must(s.Offset(pan, pin)))
	}
	o.f("    };\n\n")

	// EMV.
	o.f("    public static readonly (string Imk, string Pan, string Psn, ushort Atc, ulong Amount, string Un, string Iad, string Mk, string Sk, string Data, string Arqc18, string Arqc10, string Arpc1, string Arpc2)[] Emv =\n    {\n")
	for i := 0; i < 20; i++ {
		imk := keys.FixParity(bytesN(16))
		pan := luhnPAN(16 + rng.Intn(4))
		psn := fmt.Sprintf("%02d", rng.Intn(3))
		tx := emv.Transaction{Amount: uint64(rng.Intn(100000000)), TerminalCountry: 76, Currency: 986,
			Date: "261127", Type: 0, ATC: uint16(rng.Intn(65536)), AIP: [2]byte{0x39, 0x00}, IAD: bytesN(rng.Intn(8))}
		copy(tx.UnpredictableNum[:], bytesN(4))
		mk := must(emv.DeriveICCKey(imk, pan, psn))
		sk := must(emv.SessionKey(mk, tx.ATC))
		a18 := must(emv.ARQC(mk, tx, emv.CVN18))
		a10 := must(emv.ARQC(mk, tx, emv.CVN10))
		p1 := must(emv.ARPCMethod1(sk, a18, [2]byte{'0', '0'}))
		p2 := must(emv.ARPCMethod2(sk, a18, [4]byte{0, 0x82, 0, 0}, nil))
		o.f("        (%s, %q, %q, %d, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s),\n", hx(imk), pan, psn, tx.ATC, tx.Amount,
			hx(tx.UnpredictableNum[:]), hx(tx.IAD), hx(mk), hx(sk), hx(must(tx.Data())), hx(a18), hx(a10), hx(p1), hx(p2))
	}
	o.f("    };\n\n")

	// FF1.
	o.f("    public static readonly (string Key, string Alphabet, string Tweak, string Plain, string Cipher)[] Ff1 =\n    {\n")
	for i := 0; i < 30; i++ {
		k := bytesN([]int{16, 24, 32}[i%3])
		alpha := fpe.Digits
		if i%4 == 3 {
			alpha = fpe.Alphanumeric
		}
		f := must(fpe.NewFF1(k, alpha))
		n := f.MinLen() + rng.Intn(25)
		var b strings.Builder
		for j := 0; j < n; j++ {
			b.WriteByte(alpha[rng.Intn(len(alpha))])
		}
		tw := bytesN(rng.Intn(20))
		o.f("        (%s, %q, %s, %q, %q),\n", hx(k), alpha, hx(tw), b.String(), must(f.Encrypt(b.String(), tw)))
	}
	o.f("    };\n\n")

	// Tokens: fresh vault per PAN, so tokens depend only on the FPE key.
	o.f("    public static readonly (string FpeKey, string Pan, string Token)[] Tokens =\n    {\n")
	for i := 0; i < 20; i++ {
		k := tokenize.Keys{FPE: bytesN(32), Data: bytesN(32), MAC: bytesN(32)}
		v := must(tokenize.New(k))
		pan := luhnPAN(13 + rng.Intn(7))
		o.f("        (%s, %q, %q),\n", hx(k.FPE), pan, must(v.Tokenize(pan)))
	}
	o.f("    };\n}\n")
	os.Stdout.Write(o.b.Bytes())
}
